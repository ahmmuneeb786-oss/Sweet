import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import { VitePWA } from 'vite-plugin-pwa';

// https://vitejs.dev/config/
export default defineConfig({
  plugins: [
    react(),
    VitePWA({
      // injectManifest = our own service worker (src/sw/sw.ts) with the
      // precache list injected. The old generateSW mode wrote its own
      // dist/sw.js over public/sw.js, which dropped the push handlers in
      // production. Runtime caching (face-api, /models) now lives in sw.ts.
      strategies: 'injectManifest',
      srcDir: 'src/sw',
      filename: 'sw.ts',
      registerType: 'autoUpdate',
      // public/manifest.json (linked from index.html) is the real manifest.
      manifest: false,
      // Register the worker on `npm run dev` too, so push works on localhost
      // (localhost and the live site are separate origins with separate
      // subscriptions — both need a worker).
      devOptions: { enabled: true, type: 'module' },
      injectManifest: {
        // Caches every code asset generated by Vite for true offline app access
        globPatterns: ['**/*.{js,css,html,ico,png,svg,woff2}'],
        // ...except face-api, which only face-lock users need. It (and the
        // /models weights) is cached on first use instead — see src/sw/sw.ts.
        globIgnores: ['**/face-api-*.js'],
      },
    }),
  ],
  build: {
    rollupOptions: {
      output: {
        // Give the on-demand face-api chunk (see src/lib/faceModels.ts) a
        // stable name so the service worker can match it.
        manualChunks(id) {
          if (id.includes('node_modules/face-api.js') || id.includes('node_modules/@tensorflow')) {
            return 'face-api';
          }
        },
      },
    },
  },
  optimizeDeps: {
    exclude: ['lucide-react'],
  },
});
